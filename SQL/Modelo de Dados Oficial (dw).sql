	IdDimEnderecoInstituicao INT IDENTITY,
	Regiao VARCHAR(32) NOT NULL,
	Estado VARCHAR(64) NOT NULL,
	UF CHAR(2) NOT NULL,
	Mesorregiao VARCHAR(64) NOT NULL,
	Microrregiao VARCHAR(64) NOT NULL,
	Municipio VARCHAR(64) NOT NULL,
